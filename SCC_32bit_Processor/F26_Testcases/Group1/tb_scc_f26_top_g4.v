// Group 4 copy: only the waveform-view wires were remapped to our hierarchy
// (uut.memory.memory, uut.scc.REGS.registers; R14 = 0, R15 = PC). Checks are unchanged.
/*
* Top level testbench for the SCC. Runs whatever program is in output.mem (from the assembler) and
* checks how it ended. The program's results in memory are checked by the makefile's prog target, which
* compares scc_out.txt against the class emulator with the class SelfChecker.
* Reset is held high for 3 clocks, then the program runs until the CPU halts (halt_f), reports an
* error (err_f = 10), or a timeout is reached. On HALT, err_f should read 01 (the ISA's HALT indication),
* and both stay latched until reset. Like the class testbench, it prints "Apollo has landed" on
* HALT and "Houston we have a problem" on an error.
*
* Plusargs (passed to vvp after the .vvp file, the makefile's prog target sets these):
*   +MAX_CYCLES=<n>    Timeout in cycles (default 100000)
*   +EXPECT_ERROR      The program is supposed to end with an error (err_f = 10) instead of a HALT
*   +MEM_UNCHANGED     Every byte of memory must be unchanged from output.mem when the program ends.
*                      Used where the emulator can't check the program (error.asm, since the emulator
*                      ignores undefined instructions and would run the STOR after one)
*
* This testbench was generated by Claude after providing the original testbench and the SCC modules
*/

`timescale 1ns/1ps

module kfz_testbench;

	reg	clk;
	reg	clk_en;
	reg	rst;
	wire	halt_f;
	wire	[1:0]	err_f;
	wire	[31:0]	inst_mem_v;
	wire	[31:0]	data_mem_in_v;

	scc_f26_top uut(
		.clk(clk),
		.clk_en(clk_en),
		.rst(rst),
		.halt_f(halt_f),
		.err_f(err_f),
		.inst_mem_v(inst_mem_v),
		.data_mem_in_v(data_mem_in_v)
	);

	always begin
		#5 clk = 0;
		#5 clk = 1;
	end

	/*
	* Wires for looking at results in the waveform viewer. $dumpvars doesn't dump arrays, so the registers
	* and memory can't be seen otherwise. reg_view[n].value is Rn, and mem_view[n].value is the 32 bit word
	* at 0x400 + 4n (0x400 - 0x4FC, where every test program stores its results).
	*/
	genvar gv;
	generate
		for (gv = 0; gv < 16; gv = gv + 1) begin : reg_view
			wire [31:0] value = (gv < 14) ? uut.scc.REGS.registers[(gv < 14) ? gv : 0] : (gv == 15) ? uut.scc.pc_v : 32'd0;
		end
		for (gv = 0; gv < 64; gv = gv + 1) begin : mem_view
			wire [31:0] value = {uut.memory.memory[32'h400 + 4*gv],
			                     uut.memory.memory[32'h400 + 4*gv + 1],
			                     uut.memory.memory[32'h400 + 4*gv + 2],
			                     uut.memory.memory[32'h400 + 4*gv + 3]};
		end
	endgenerate

	localparam integer MEM_SIZE = 2**16;          // Same size as the memory model
	localparam integer MAX_ERRORS_SHOWN = 20;     // Stop printing memory mismatches after this many

	// Internal variables for self checking
	integer errors = 0;
	integer mem_errors = 0;
	integer cycles = 0;
	integer max_cycles;
	integer i;
	reg [7:0] golden [0:MEM_SIZE-1];   // Memory as loaded from output.mem, before the program runs
	reg expect_error;
	reg mem_unchanged;
	reg halted;    // Sampled halt_f
	reg [1:0] err; // Sampled err_f

	initial begin
		$dumpvars(0, kfz_testbench);

		// Settings from the plusargs
		if (!$value$plusargs("MAX_CYCLES=%d", max_cycles)) max_cycles = 100000;
		expect_error  = $test$plusargs("EXPECT_ERROR");
		mem_unchanged = $test$plusargs("MEM_UNCHANGED");

		// Golden copy of the program, to check memory against with +MEM_UNCHANGED
		$readmemh("output.mem", golden);

		clk_en = 1;

		// Reset high for 3 clocks, then low so the test can start
		rst = 1;
		repeat(3) @(posedge clk);
		#1 rst = 0;

		// Run until HALT, an error, or the timeout
		halted = 0;
		err = 2'b00;
		while (!halted && err == 2'b00 && cycles < max_cycles) begin
			@(posedge clk);
			cycles = cycles + 1;
			#1;
			halted = halt_f;
			err = err_f;
		end
		repeat(2) @(posedge clk); // Let the memory model finish writing scc_out.txt

		// How the program ended
		if (err == 2'b10) begin
			$display("Houston we have a problem (err_f = %b after %0d cycles)", err, cycles);
			if (!expect_error) errors = errors + 1;
		end else if (halted) begin
			$display("Apollo has landed (HALT after %0d cycles)", cycles);
			if (expect_error) begin
				$display("ERROR: expected the program to end with an error, but it halted");
				errors = errors + 1;
			end
			if (halt_f !== 1'b1 || err_f !== 2'b01) begin
				$display("ERROR: after HALT expected halt_f = 1 and err_f = 01 (latched), got %b and %b", halt_f, err_f);
				errors = errors + 1;
			end
		end else begin
			$display("ERROR: timed out after %0d cycles without a HALT", cycles);
			errors = errors + 1;
		end

		// Memory unchanged from output.mem (instructions and data)
		if (mem_unchanged) begin
			for (i = 0; i < MEM_SIZE; i = i + 1) begin
				if (uut.memory.memory[i] !== golden[i]) begin
					if (mem_errors < MAX_ERRORS_SHOWN) begin
						$display("ERROR: memory[0x%h] expected %h, got %h", i, golden[i], uut.memory.memory[i]);
					end
					mem_errors = mem_errors + 1;
				end
			end
			if (mem_errors > MAX_ERRORS_SHOWN) begin
				$display("... %0d more memory mismatches not shown", mem_errors - MAX_ERRORS_SHOWN);
			end
			if (mem_errors == 0) begin
				$display("PASS: memory is unchanged");
			end
			errors = errors + mem_errors;
		end

		if (errors == 0) begin
			$display("SUCCESS: program ended as expected after %0d cycles!", cycles);
		end else begin
			$display("FAILURE: Found %0d errors.", errors);
			$fatal(1); // Non-zero exit code so make stops
		end
		$finish;
	end

endmodule
