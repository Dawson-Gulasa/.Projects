ucode_controller UCODE_CONTROLLER (
    .clk (clk),
    .rst (rst),
    .clk_en (clk_en),
    .is_mul (is_mul),
    .mul_set_flags (mul_set_flags),
    .mul_rd_addr_v (rd_addr_v),
    .mul_operand_a_v (reg_read_data_1_v),
    .mul_operand_b_v (mul_operand_b_v),
    .ucode_addr_v (ucode_addr_v),
