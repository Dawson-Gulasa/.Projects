    .ucode_c_f (ucode_c_f),
    .ucode_v_f (ucode_v_f)
);

//================================
// SIGNED DIVISION CONTROLLER
//============================
// The division controller performs DIV/DIVS independently of the existing MUL controller.
//
// Operand A comes from the first register-file
// source read port.
//
// Operand B uses the same register/immediate selection convention as ordinary ALU and MUL instructions.
//
// The controller captures both operands before executing its multicycle operation, so later
// register-file changes cannot alter the result.
//
// Division produces two writeback requests:
// - Quotient to the decoded destination Rd.
// - Remainder to architectural register R12.
//
// The controller also supplies:
// - Fetch-stall indication.
// - Divide-by-zero exception indication.
// - Optional DIVS NZCV flag update.
//
//================================
// DIVISION OPERAND SELECTION
//===============================
// This wrapper introduces no architectural register or flag storage.
//
// SCC combines multiplication and division stalls to control IF.
// WB_STAGE selects the final register-writeback and NZCV sources.
//
// DIV uses an immediate operand when use_imm is asserted.
// Otherwise, the second register-file read value supplies operand B.

wire [31:0] div_operand_b_v;

assign div_operand_b_v = use_imm ? imm_v : reg_read_data_2_v;

div_controller DIV_CONTROLLER (
    // System control.
    .clk (clk),
    .rst (rst),
    .clk_en (clk_en),

    // Decoded DIV/DIVS instruction.
    .is_div (is_div),
    .div_set_flags (div_set_flags),

    // Architectural destination and operands.
    .div_rd_addr_v (rd_addr_v),
    .div_operand_a_v (reg_read_data_1_v),
    .div_operand_b_v (div_operand_b_v),

    // The controller selects the micro-PC.
    // The ROM returns an assembled instruction.
    // This path is separate from the existing multiplication microcode controller.
    .div_ucode_addr_v (div_ucode_addr_v),
    .div_ucode_inst_v (div_ucode_inst_v),

    // Multicycle execution and exception status.
    .div_stall (div_stall),
    .div_error (div_error),

    // Quotient/remainder writeback requests.
    .div_reg_write_en (div_reg_write_en),
    .div_reg_write_addr_v (div_reg_write_addr_v),
    .div_reg_write_data_v (div_reg_write_data_v),

    // Optional DIVS flag update.
    .div_flags_write_en (div_flags_write_en),
    .div_n_f (div_n_f),
    .div_z_f (div_z_f),
    .div_c_f (div_c_f),
    .div_v_f (div_v_f)
);

//=================================
// STACK OCCUPANCY CONTROLLER
//==============================
// This leaf module tracks the number of valid stack entries from zero through 16.
//
// It does not store the architectural stack pointer or any stack data.
//
// Architectural state ownership:
// - stack_controller owns occupancy.
// - regs.v owns R13.
// - flags.v owns the S status flag.
// - Normal data memory owns stack contents.
//
// PUSH/POP decoding supplies the requests.
//
// The integrated stack datapath and SCC control paths coordinate occupancy changes with architectural PUSH/POP execution so that
// the stack depth updates once per executed instruction.

stack_controller STACK_CONTROLLER (
    .clk (clk),
    .rst (rst),
    .clk_en (clk_en),

    .push_en (stack_push_request),
    .pop_en (stack_pop_request),

    .stack_depth_v (stack_depth_v),
    .stack_full (stack_full),
    .stack_empty (stack_empty)
);

//=================================
// COMBINATIONAL STACK DATAPATH
//==================================
// Calculate PUSH/POP addresses, data, and architectural register update requests.
//
// Architectural state is not stored here:
// - regs.v owns the R13 stack pointer.
// - stack_controller.v owns occupancy.
// - flags.v owns the S status flag.
// - The shared data memory stores stack data.
//
// PUSH uses the existing dedicated register
// read port, which selects instruction bits
// [24:21]. These bits identify the register
// whose value must be pushed.
//
// POP obtains its result from the shared data-memory read interface.
//
// The stack datapath produces combinational requests only. Memory strobes and actual
// architectural writes are coordinated outside this leaf module.
//
// This module is intentionally kept separate from the existing ordinary EXE datapath.

stack_datapath STACK_DATAPATH (
    .is_push (stack_push_request),
    .is_pop (stack_pop_request),

    // Current architectural stack pointer.
    .stack_sp_v (stack_sp_v),

    // Occupancy and stack boundary status.
    .stack_depth_v (stack_depth_v),
    .stack_full (stack_full),
    .stack_empty (stack_empty),

    // PUSH obtains data from the register file.
    .push_data_v (store_read_data_v),

    // POP receives the memory-read result.
    .data_mem_in_v (data_mem_in_v),

    // Stack-memory requests and data.
    .stack_mem_rd_request (stack_mem_rd_request),
    .stack_mem_wr_request (stack_mem_wr_request),
    .stack_mem_addr_v (stack_mem_addr_v),
    .stack_mem_out_v (stack_mem_out_v),

    // Architectural R13 update request.
    .stack_sp_write_en (stack_sp_write_en),
    .stack_sp_next_v (stack_sp_next_v),

    // POP destination-register writeback.
    .stack_pop_write_en (stack_pop_write_en),
    .stack_pop_data_v (stack_pop_data_v)
);

endmodule
