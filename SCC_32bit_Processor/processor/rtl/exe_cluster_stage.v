// exe_cluster_stage.v
// Structural stage wrapper. Preserves original leaf module behavior.
// All internal signals are wires; architectural state remains in leaf modules

module exe_cluster_stage (
    output wire alu_c_f,
    output wire alu_n_f,
    input wire [2:0] alu_op_v,
    output wire alu_v_f,
    output wire alu_z_f,
    input wire clk,
    input wire clk_en,
    output wire [31:0] data_mem_addr_v,
    input wire [31:0] data_mem_in_v,
    output wire [31:0] data_mem_out_v,
    input wire data_mem_rd_en,
    output wire [3:0] exe_reg_write_addr_v,
    output wire [31:0] exe_reg_write_data_v,
    output wire exe_reg_write_en,
    input wire [31:0] imm_v,
    input wire is_alu,
    input wire is_clr,
    input wire is_load_store,
    input wire is_lsl,
    input wire is_lsr,
    input wire is_mov,
    input wire is_movt,
    input wire is_mul,

    // ID_STAGE identifies the current signed division instruction.
    // is_div selects DIV or DIVS. div_set_flags is instruction bit 28 and
    // distinguishes DIVS from ordinary DIV.
    // These inputs do not modify the existing multiplication instruction controls.

    input wire is_div,
    input wire div_set_flags,

    input wire is_set,

    //=================================
    // STACK INSTRUCTION CONTROLS
    //====================================
    // These signals originate from id_stage.v.
    //
    // The stack controller tracks the number of valid entries in the 16-word stack.
    //
    // Stack memory addressing and architectural R13 update requests are generated by the stack datapath and committed through
    // the shared memory and register writeback paths.
    input wire is_push,
    input wire is_pop,

    // Current architectural stack occupancy
    output wire [4:0] stack_depth_v,
    output wire stack_full,
    output wire stack_empty,

    //=====================================
    // ARCHITECTURAL STACK POINTER
    //===================================
    // Current R13 value supplied directly by the architectural register file.
    // The EXE stage may calculate the next stack pointer but does not store R13.

    input wire [31:0] stack_sp_v,

    input wire [31:0] mul_operand_b_v,
    input wire mul_set_flags,
    input wire [3:0] rd_addr_v,
    input wire [31:0] reg_read_data_1_v,
    input wire [31:0] reg_read_data_2_v,
    input wire reg_write_en,
    input wire rst,
    input wire [31:0] store_read_data_v,
    output wire ucode_c_f,
    output wire ucode_n_f,
    output wire [3:0] ucode_reg_write_addr_v,
    output wire [31:0] ucode_reg_write_data_v,
    output wire ucode_reg_write_en,
    output wire ucode_set_flags,
    output wire ucode_stall,

    output wire ucode_v_f,
    output wire ucode_z_f,

    //===========================
    // DIVISION RESULT INTERFACE
    //============================
    // DIV_CONTROLLER produces registered quotient and remainder results.
    // The controller requests separate architectural writes to Rd and R12.
    //
    // WB_STAGE selects these results ahead of POP and ordinary writeback.
    // SCC only connects the execution outputs to the WB interface.
    //
    // DIV_CONTROLLER does not directly modify architectural registers.

    output wire div_stall,
    output wire div_error,

    output wire div_reg_write_en,
    output wire [3:0] div_reg_write_addr_v,
    output wire [31:0] div_reg_write_data_v,

    output wire div_flags_write_en,
    output wire div_n_f,
    output wire div_z_f,
    output wire div_c_f,
    output wire div_v_f,

    input wire use_imm,

    //==============================
    // STACK MEMORY INTERFACE
    //========================
    // These combinational stack requests connect to the shared architectural data-memory interface through the parent SCC.
    // The stack controller and datapath do not store memory data.

    output wire stack_mem_rd_request,
    output wire stack_mem_wr_request,

    output wire [31:0] stack_mem_addr_v,
    output wire [31:0] stack_mem_out_v,

    //===============================
    // STACK REGISTER INTERFACE
    //============================
    // Request to update architectural R13 and the next pointer value.

    output wire stack_sp_write_en,
    output wire [31:0] stack_sp_next_v,

    // POP result selection and data.
    //
    // The final writeback mux will combine these outputs with normal EXE and
    // microcode register writes.

    output wire stack_pop_write_en,
    output wire [31:0] stack_pop_data_v
);

// Internal interconnects between unchanged leaf modules
wire [1:0] ucode_addr_v;
wire [31:0] ucode_inst_v;


// The division controller selects the current microinstruction address.
// DIV_UCODE_ROM supplies the corresponding assembled 32-bit instruction.
// No architectural state is stored in this structural execution-stage wrapper.

wire [1:0] div_ucode_addr_v;
wire [31:0] div_ucode_inst_v;

//==============================
// CP5 DIVISION MICROCODE ROM
//==============================
// This ROM loads div_ucode.mem, assembled from assembly/ucode_div.asm.
// The controller owns the micro-PC and decodes each microinstruction before
// advancing or committing results.
// The ROM does not directly drive REGS, FLAGS, or the architectural memory bus.

div_ucode_rom DIV_UCODE_ROM (
    .div_ucode_addr_v (div_ucode_addr_v),
    .div_ucode_inst_v (div_ucode_inst_v)
);

//===============================
// STACK OCCUPANCY REQUESTS
//=============================
// The stack controller advances only when an actual stack instruction is selected.
// During multicycle microcode execution, the current instruction is held in IF.
// Suppressing stack requests during a stall prevents unintended occupancy changes.
//
// Reset and clock-enable qualification are handled synchronously by stack_controller.v.
//
// Occupancy requests are qualified to prevent repeated PUSH/POP updates during multicycle instruction stalls.
// Architectural R13 updates and memory accesses are coordinated through the stack datapath and parent SCC writeback logic.
wire stack_push_request;
wire stack_pop_request;

assign stack_push_request = is_push && !ucode_stall;
assign stack_pop_request  = is_pop  && !ucode_stall;

