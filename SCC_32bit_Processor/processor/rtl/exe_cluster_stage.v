    .is_load_store (is_load_store),
    .data_mem_in_v (data_mem_in_v),
    .data_mem_rd_en (data_mem_rd_en),
    .is_clr (is_clr),
    .is_set (is_set),
    .is_lsl (is_lsl),
    .is_lsr (is_lsr),
    .reg_write_en_out (exe_reg_write_en),
    .reg_write_addr_v (exe_reg_write_addr_v),
    .reg_write_data_v (exe_reg_write_data_v),
    .data_mem_addr_v (data_mem_addr_v),
