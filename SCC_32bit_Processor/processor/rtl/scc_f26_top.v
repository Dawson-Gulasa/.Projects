// scc_f26_top.v
// Structural system-level top module for the SCC processor.
//
// Responsibilities:
// - Instantiate the SCC processor.
// - Instantiate the combined instruction/data memory.
// - Connect instruction-fetch addresses and data.
// - Connect data-memory addresses, data, and controls.
// - Provide clock, clock enable, and reset to the processor.
// - Expose processor status and memory read values.
//
// System Architecture:
// - scc.v contains the processor datapath, register file,
//   instruction stages, architectural flags, and controls.
// - Instruction_and_data.v models the combined memory.
// - This module connects the two components without
//   implementing additional processor behavior.
//
// Design Notes:
// - No architectural registers are declared in this module.
// - All internal connections are Verilog wires.
// - The SCC generates memory addresses and control signals.
// - The memory model returns instruction and data values.
// - The SCC generates HALT and error/status indications.
// - The top-level ports preserve the original SCC interface.

module scc_f26_top (
    // System clock supplied to the processor and memory model
    input clk,

    // Processor clock enable
    input clk_en,

    // Processor reset
    input rst,

    // Asserted when the current processor instruction is HALT
    output halt_f,

    // Encoded processor status:
    // 00 = Normal operation
    // 01 = HALT
    // 10 = Illegal instruction
    // 11 = Reserved
    output [1:0] err_f,

    // Current instruction returned by the instruction memory
    output [31:0] inst_mem_v,

    // Current read-data value returned by the data memory
    output [31:0] data_mem_in_v
);

//====================================
// SCC-TO-MEMORY INTERCONNECT SIGNALS
//=====================================
// These wires form the external memory interface of
// the SCC processor.
//
// The SCC generates instruction addresses and read enable,
// while the memory model returns the requested instruction.
//
// For data accesses, the SCC generates the address,
// write data, and read/write enable signals.
//
// The memory module is responsible for completing
// reads and writes according to its own memory model.

// Instruction-memory read enable
wire inst_mem_en;

// Instruction-memory address generated by the SCC IF stage
wire [31:0] inst_mem_addr_v;

// Data-memory address generated by the SCC EXE stage
wire [31:0] data_mem_addr_v;

// Data value provided by the SCC for memory stores
wire [31:0] data_mem_out_v;

// Data-memory read enable
wire data_mem_rd_en;

// Data-memory write enable.
// Generated by the SCC memory-write controller
wire data_mem_wr_en;

//==========================
// SCC PROCESSOR INSTANCE
//===========================
// The processor contains the instruction fetch/decode
// stages, execution logic, architectural registers,
// NZCV flags, branch evaluation, and multiplication
// microcode controller.
//
// The processor receives instruction/data read values
// from the combined memory model.
//
// It generates instruction and data-memory addresses,
// memory access controls, write data, and status.
//
// Processor storage and sequential control remain
// inside the appropriate SCC subordinate modules.

scc scc (
    // System control
    .clk (clk),
    .clk_en (clk_en),
    .rst (rst),

    // Memory read values supplied to the processor
    .inst_mem_v (inst_mem_v),
    .data_mem_in_v (data_mem_in_v),

    // Processor status outputs
    .err_f (err_f),
    .halt_f (halt_f),

    // Instruction-memory interface
    .inst_mem_en (inst_mem_en),
    .inst_mem_addr_v (inst_mem_addr_v),

    // Data-memory interface
    .data_mem_addr_v (data_mem_addr_v),
    .data_mem_out_v (data_mem_out_v),
    .data_mem_rd_en (data_mem_rd_en),
    .data_mem_wr_en (data_mem_wr_en)
);

//================================================
// COMBINED INSTRUCTION AND DATA-MEMORY INSTANCE
//=================================================
// The memory module provides the instruction and data
// storage used by the SCC simulation environment.
//
// Instruction-memory operations:
// - Receive an instruction address from the processor.
// - Return the corresponding instruction word.
//
// Data-memory operations:
// - Receive the processor-generated data address.
// - Return memory data when a read is requested.
// - Store processor-generated write data when a write
//   operation is requested.
//
// The memory model also receives the processor HALT
// signal for its simulation output/dump functionality.
//
// Memory behavior and initialization are defined
// within Instruction_and_data.v, not in this module.
//
// The memory receives clk_mem as part of its interface;
// the current memory model defines its own access timing.

instruction_and_data memory (
    // Memory interface signals.
    .clk_mem (clk),
    .halt_f (halt_f),

    // Instruction-memory access.
    .inst_mem_en (inst_mem_en),
    .inst_mem_addr_v (inst_mem_addr_v),

    // Data-memory access.
    .data_mem_addr_v (data_mem_addr_v),
    .data_mem_rd_en (data_mem_rd_en),
    .data_mem_wr_en (data_mem_wr_en),
    .data_mem_out_v (data_mem_out_v),

    // Instruction/data values returned to the processor.
    .inst_mem_v (inst_mem_v),
    .data_mem_in_v (data_mem_in_v)
);

endmodule
