`timescale 1ns/1ps
// tb_cp5_array_stats_portable.v
//   Portable, self-checking testbench for the SCC Array Statistics program.
//
// PURPOSE:
//   Verify that an SCC processor correctly executes assembly/array_stats_mul.asm
//   and produces the expected results for an eight-element integer array.
//
//   The assembly program performs five calculations:
//     1. Sum of the array elements
//     2. Minimum array element
//     3. Maximum array element
//     4. Number of even elements
//     5. Weighted checksum calculated using MUL instructions
//
//   Results are verified by reading scc_out.txt, which is generated by the
//   class Instruction_and_data.v memory model when execution reaches HALT.
//
//   Since the published top-level interface does not expose internal MUL
//   writeback transactions, this test verifies final architectural results
//   rather than the number of internal multiplication writebacks.
//
// SETUP:
//   1. Assemble assembly/array_stats_mul.asm into output.mem.
//   2. Compile this testbench with the SCC top-level and required RTL.
//   3. Run the simulation from the directory containing output.mem.
//   4. Confirm that all six checks pass with zero errors.
//
// EXPECTED RESULTS:
//   Input array: {9, 2, 7, 4, 1, 8, 3, 6}
//
//   Address       Description             Expected decimal value
//   0x0000D640    Array sum               40
//   0x0000D644    Array minimum           1
//   0x0000D648    Array maximum           9
//   0x0000D64C    Even element count      4
//   0x0000D650    Weighted MUL checksum   172
//
// PASS CRITERIA:
//   - Processor reaches normal architectural HALT (err_f = 2'b01).
//   - All five result addresses exist in the memory dump.
//   - Every stored result matches the expected value.
//   - Exactly six verification checks complete with zero errors.

module tb_cp5_array_stats_portable;

    //============================
    // TEST CONFIGURATION
    //==============================
    // The assembly program writes five consecutive 32-bit results beginning
    // at RESULT_BASE. Each result occupies four bytes.
    //
    // TIMEOUT_NS prevents an infinite simulation if the processor fails
    // to reach HALT due to an instruction, branch, or control-path error.

    localparam [31:0] RESULT_BASE = 32'h0000_D640;
    localparam integer RESULT_COUNT = 5;
    localparam integer TIMEOUT_NS = 100000;

    //====================================
    // CLASS-DEFINED PROCESSOR SIGNALS
    //======================================
    // The testbench generates clk, clk_en, and rst.
    //
    // halt_f and err_f indicate processor completion and error status.
    // inst_mem_v and data_mem_in_v are included because they are part of
    // the required scc_f26_top interface.

    reg clk;
    reg clk_en;
    reg rst;
    wire halt_f;
    wire [1:0] err_f;
    wire [31:0] inst_mem_v;
    wire [31:0] data_mem_in_v;

    //=============================
    // VERIFICATION VARIABLES
    //=============================
    // checks/errors: Total completed checks and detected failures.
    // cycles: Informational processor clock-cycle counter.
    //
    // fd: File descriptor for the memory dump.
    // scan_count: Number of successfully parsed fields from a line.
    // index: Result-array index calculated from a memory address.
    // i: General-purpose loop index.
    //
    // observed[]: Actual values read from scc_out.txt.
    // found[]: Indicates whether each expected address was located.
    // expected[]: Correct results independently known from the program.

    integer checks;
    integer errors;
    integer cycles;
    integer fd;
    integer scan_count;
    integer index;
    integer i;
    reg [8*128-1:0] header_line;
    reg [31:0] addr_v;
    reg [31:0] data_v;
    reg [31:0] observed [0:RESULT_COUNT-1];
    reg found [0:RESULT_COUNT-1];

    // Expected values are fixed by array_stats_mul.asm:
    // input = {9,2,7,4,1,8,3,6}; weighted sum = 172.
    // Addresses: D640, D644, D648, D64C, D650.
    reg [31:0] expected [0:RESULT_COUNT-1];

    //========================================================
    // DEVICE UNDER TEST - CLASS-DEFINED TOP-LEVEL INTERFACE
    //=========================================================
    // Connect only published ports of scc_f26_top.

    scc_f26_top DUT (
        .clk (clk),
        .clk_en (clk_en),
        .rst (rst),
        .halt_f (halt_f),
        .err_f (err_f),
        .inst_mem_v (inst_mem_v),
        .data_mem_in_v (data_mem_in_v)
    );

    //===========================
    // CLOCK GENERATION
    //=============================
    // Generate a 10 ns clock period

    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end

    //================================
    // EXECUTION CYCLE COUNTER
    //=================================
    // Count enabled positive clock edges while the processor is running.
    // Reset clears the counter.
    //
    // The cycle count is informational; pass/fail depends on architectural
    // status and stored results, not on a group-specific execution latency.

    always @(posedge clk) begin
        if (rst)
            cycles <= 0;
        else if (clk_en && !halt_f)
            cycles <= cycles + 1;
    end

    //====================================
    // GENERAL 32-BIT SELF-CHECKING TASK
    //===================================
    // Compare an observed value against its expected value.
    //
    // The !== operator intentionally treats unknown (X) and high-impedance
    // (Z) bits as verification failures. These must never silently pass.
    //
    // Each call increments checks and prints a PASS or FAIL diagnostic.

    task check32;
        input [31:0] actual;
        input [31:0] wanted;
        input [8*72-1:0] description;
        begin
            checks = checks + 1;
            if (actual !== wanted) begin
                errors = errors + 1;
                $display("FAIL: %0s expected=%08h actual=%08h", description, wanted, actual);
            end else begin
                $display("PASS: %0s = %08h", description, actual);
            end
        end
    endtask

    //==================================================
    // READ ARCHITECTURAL RESULTS FROM THE MEMORY DUMP
    //==================================================
    // The class memory model writes scc_out.txt after HALT.
    //
    // Example format:
    //   Address,Value
    //   0x0000d640,0x00000028
    //
    // This task searches the dump for the five specified result addresses.
    // All other memory locations are ignored.
    //
    // Address-to-index calculation:
    //   index = (address - RESULT_BASE) / 4
    //
    // For example:
    // 0xD640 -> index 0
    // 0xD644 -> index 1
    // 0xD650 -> index 4
    //
    // Only word-aligned addresses are accepted.
    //
    // Each found[] flag distinguishes a missing result from a valid result
    // that happens to contain zero.



    task read_results;
        begin
            for (i = 0; i < RESULT_COUNT; i = i + 1) begin
                observed[i] = 32'hxxxx_xxxx;
                found[i] = 1'b0;
            end

            fd = $fopen("scc_out.txt", "r");
            if (fd == 0) begin
                errors = errors + 1;
                $display("FAIL: scc_out.txt was not produced on HALT");
            end else begin
                scan_count = $fgets(header_line, fd);
                while (!$feof(fd)) begin
                    scan_count = $fscanf(fd, "0x%h,0x%h\n", addr_v, data_v);
                    if (scan_count == 2) begin
                        if ((addr_v >= RESULT_BASE) && (addr_v < RESULT_BASE + RESULT_COUNT * 4) && (addr_v[1:0] == 2'b00)) begin
                            index = (addr_v - RESULT_BASE) / 4;
                            observed[index] = data_v;
                            found[index] = 1'b1;
                        end
                    end else if (!$feof(fd)) begin
                        errors = errors + 1;
                        $display("FAIL: Malformed memory dump line");
                        $fclose(fd);
                        disable read_results;
                    end
                end
                $fclose(fd);
            end
        end
    endtask

    //================================================
    // MAIN TEST SEQUENCE - RESET, EXECUTE, VERIFY
    //===============================================

    initial begin

        // Enable waveform dumping
        $dumpfile("tb_cp5_array_stats_portable.vcd");
        $dumpvars(0, tb_cp5_array_stats_portable);

        // Initialize system controls and verification counters.
        // Keep clk_en asserted for the entire application run.

        rst = 1'b1;
        clk_en = 1'b1;
        checks = 0;
        errors = 0;
        cycles = 0;

        // Populate the expected architectural results.
        // These values must match the intended assembly algorithm.

        expected[0] = 32'd40; // Sum
        expected[1] = 32'd1; // Minimum
        expected[2] = 32'd9; // Maximum
        expected[3] = 32'd4; // Even elements
        expected[4] = 32'd172; // Weighted MUL checksum

        // Hold reset for three positive edges to initialize the processor
        // Release reset on a negative edge, away from sequential updates

        repeat (3) @(posedge clk);
        @(negedge clk);
        rst = 1'b0;

        //===========================================
        // WAIT FOR STABLE ARCHITECTURAL COMPLETION
        //==========================================
        // The instruction memory and instruction decoder are combinational.
        // During a PC/instruction update, temporary decoded values can occur
        // before all signals settle.
        //
        // Waiting directly for a halt_f transition could therefore react to
        // a short transient instead of the final architectural instruction.
        //
        // To avoid this, we sample err_f after each negative clock edge and
        // allow 1 ns for combinational outputs to settle.
        //
        // Architectural status values:
        // 2'b00 = Processor executing normally
        // 2'b01 = Normal HALT instruction encountered
        // 2'b10 = Architectural error
        //
        // The loop exits on either completion or an architectural error.
        // A separate timeout process catches nonterminating execution

        while ((err_f !== 2'b01) && (err_f !== 2'b10)) begin
            @(negedge clk);
            #1;
        end

        // Give the memory model time to complete its HALT-triggered dump
        // before attempting to open and parse scc_out.txt.

        #3;
        check32({30'd0, err_f}, 32'd1, "Normal HALT status");

        //=================================
        // VERIFY THE FIVE STORED RESULTS
        //================================
        // Check memory only after normal HALT.
        //
        // When an architectural error occurs, the status check fails and
        // the final test summary reports failure.
        //
        // For every expected address:
        //   - Check that the address appears in the output file.
        //   - Compare its observed data with the expected value.
        //   - Print PASS/FAIL and update the verification counters.

        if (err_f === 2'b01) begin
            read_results();
            for (i = 0; i < RESULT_COUNT; i = i + 1) begin
                checks = checks + 1;
                if (!found[i]) begin
                    errors = errors + 1;
                    $display("FAIL: Missing result address %08h", RESULT_BASE + i*4);
                end else if (observed[i] !== expected[i]) begin
                    errors = errors + 1;
                    $display("FAIL: Result[%0d] expected=%08h actual=%08h", i, expected[i], observed[i]);
                end else begin
                    $display("PASS: Result[%0d] at %08h = %08h", i, RESULT_BASE + i*4, observed[i]);
                end
            end
        end

        //=============================
        // FINAL VERIFICATION SUMMARY
        //================================
        // Expected check count:
        //   1 normal HALT status check
        //   5 architectural result checks
        //   6 total checks

        $display("\nCP5 PORTABLE ARRAY STATS: checks=%0d errors=%0d cycles=%0d", checks, errors, cycles);
        if ((checks == 6) && (errors == 0))
            $display("CP5 PORTABLE ARRAY STATS TEST PASSED");
        else
            $display("CP5 PORTABLE ARRAY STATS TEST FAILED");
        $finish;
    end

    //====================
    // SIMULATION WATCHDOG
    //=======================
    // Stop the simulation if no valid completion occurs before TIMEOUT_NS.
    // This prevents a branch/control bug from creating an infinite run.
    //
    // TIMEOUT_NS is a simulation-time limit, not a CPU instruction count

    initial begin
        #TIMEOUT_NS;
        $display("FAIL: CP5 portable Array Statistics timeout");
        $display("CP5 PORTABLE ARRAY STATS TEST FAILED");
        $finish;
    end

endmodule
