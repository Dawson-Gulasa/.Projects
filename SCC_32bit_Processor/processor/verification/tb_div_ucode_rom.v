`timescale 1ns/1ps
// tb_div_ucode_rom.v
// Standalone verification of the four-word division microcode ROM.
// Requires div_ucode.mem in the simulator working directory.
// This test intentionally does not instantiate the processor or controller.

module tb_div_ucode_rom;
    reg [1:0] div_ucode_addr_v;
    wire [31:0] div_ucode_inst_v;
    integer checks;
    integer errors;

    div_ucode_rom DUT (
        .div_ucode_addr_v(div_ucode_addr_v),
        .div_ucode_inst_v(div_ucode_inst_v)
    );

    task check_instruction;
        input [1:0] word_addr;
        input [31:0] expected_word;
        input [8*64-1:0] description;
        begin
            div_ucode_addr_v = word_addr;
            #1; // Allow combinational ROM read to settle.
            checks = checks + 1;
            if (div_ucode_inst_v !== expected_word) begin
                errors = errors + 1;
                $display("FAIL: %0s address=%0d expected=%08h actual=%08h", description, word_addr, expected_word, div_ucode_inst_v);
            end else begin
                $display("PASS: %0s address=%0d instruction=%08h", description, word_addr, div_ucode_inst_v);
            end
        end
    endtask

    initial begin
        checks = 0;
        errors = 0;
        div_ucode_addr_v = 2'd0;

        // Expected opcodes are generated by the current class assembler:
        // CLR R12; DIV R0,R0,R0; NOP; HALT.
        check_instruction(2'd0, 32'h0580_0000, "Initialize marker (CLR R12)");
        check_instruction(2'd1, 32'h6E00_0000, "Division marker (DIV R0,R0,R0)");
        check_instruction(2'd2, 32'hC800_0000, "Quotient marker (NOP)");
        check_instruction(2'd3, 32'hD000_0000, "Completion marker (HALT)");

        $display("\nCP5 DIV UCODE ROM: checks=%0d errors=%0d", checks, errors);
        if ((checks == 4) && (errors == 0))
            $display("CP5 DIV UCODE ROM TEST PASSED");
        else
            $display("CP5 DIV UCODE ROM TEST FAILED");
        $finish;
    end
endmodule
